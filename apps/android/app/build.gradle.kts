val selfFormingKeystore = providers.environmentVariable("SELF_FORMING_KEYSTORE_PATH").orNull
val selfFormingPassword = providers.environmentVariable("SELF_FORMING_KEYSTORE_PASSWORD").orNull
val signingRequired = providers.environmentVariable("SELF_FORMING_SIGNING_REQUIRED").orNull == "true"
val signInScheme = "selfforming"
check(!signingRequired || (!selfFormingKeystore.isNullOrBlank() && !selfFormingPassword.isNullOrBlank())) {
    "Distributed APKs require the persistent Self Forming signing key. Configure the repository signing secrets."
}
check((selfFormingKeystore == null) == (selfFormingPassword == null)) { "Incomplete Self Forming signing configuration" }
// Versioning guard: no silent default. Every installable APK needs an explicit, increasing versionCode
// (apps/android/gradle.properties, or -PselfFormingVersionCode=N), or Android refuses the update.
val selfFormingVersionCode = providers.gradleProperty("selfFormingVersionCode").orNull?.trim()?.toIntOrNull()
    ?.takeIf { it in 1..2100000000 }
    ?: throw GradleException("selfFormingVersionCode is missing or invalid: set it in apps/android/gradle.properties (increase it for every APK).")

val browserAssets = rootProject.layout.projectDirectory.dir("../../dist/app")
val generatedAssets = layout.buildDirectory.dir("generated/selfFormingAssets")
val syncBrowserAssets by tasks.registering(Sync::class) {
    from(browserAssets)
    into(generatedAssets.map { it.dir("web") })
    doFirst {
        check(browserAssets.file("index.html").asFile.isFile) {
            "Browser assets missing. Run the web build (scripts/build.mjs) at the repository root first."
        }
    }
}

// Built-in plugins own their Kotlin half (docs/plugins.md §3a): plugins/<id>/native/src/** (same package,
// md.incept.selfforming) is compiled statically into the APK, never dex-loaded, and an optional
// plugins/<id>/native/manifest.xml fragment is merged into the APK manifest. A tree without a plugin
// folder simply builds without its Kotlin half. native/test and native/androidTest hold its JVM/device tests.
val builtinNative = (rootProject.file("../../plugins").listFiles() ?: emptyArray<File>())
    .filter { it.resolve("native").isDirectory }.sortedBy { it.name }.map { it.resolve("native") }
fun builtinDirs(name: String) = builtinNative.map { it.resolve(name) }.filter { it.isDirectory }

// Native route registry (R1): each plugin folder's Kotlin half declares `internal object <PascalCaseId>Native :
// BuiltinNative` (core-self-update -> CoreSelfUpdateNative.kt). The host reaches them only through the generated
// BuiltinNatives.ALL, so dropping a plugin folder needs no host edit. Folders without that file contribute none.
val builtinNativeObjects = builtinNative.mapNotNull { native ->
    val name = native.parentFile.name.split('-').joinToString("") { it.replaceFirstChar(Char::uppercaseChar) } + "Native"
    name.takeIf { native.resolve("src").walkTopDown().any { it.isFile && it.name == "$name.kt" } }
}
abstract class GenerateBuiltinNatives : DefaultTask() {
    @get:Input abstract val objects: ListProperty<String>
    @get:OutputDirectory abstract val output: DirectoryProperty
    @TaskAction fun generate() {
        val dir = output.get().asFile.resolve("md/incept/selfforming")
        dir.mkdirs()
        dir.resolve("BuiltinNatives.kt").writeText(
            "// Generated by apps/android/app/build.gradle.kts from plugins/*/native (R1). Do not edit.\n" +
            "package md.incept.selfforming\n\n" +
            "internal object BuiltinNatives {\n" +
            "    val ALL: List<BuiltinNative> = listOf(" + objects.get().joinToString(", ") + ")\n" +
            "}\n")
    }
}
val generateBuiltinNatives by tasks.registering(GenerateBuiltinNatives::class) {
    objects.set(builtinNativeObjects)
    output.set(layout.buildDirectory.dir("generated/builtinNatives"))
}

android {
    namespace = "md.incept.selfforming"
    compileSdk = 36
    defaultConfig {
        applicationId = "md.incept.selfforming"
        minSdk = 28
        targetSdk = 36
        versionCode = selfFormingVersionCode
        versionName = "0.7.0"
        manifestPlaceholders["signInScheme"] = signInScheme
        buildConfigField("String", "SIGN_IN_SCHEME", "\"$signInScheme\"")
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        ndk { abiFilters += listOf("arm64-v8a") }
    }
    buildFeatures { buildConfig = true }
    signingConfigs {
        if (selfFormingKeystore != null) create("selfForming") {
            storeFile = file(selfFormingKeystore)
            storeType = "PKCS12"
            storePassword = selfFormingPassword
            keyAlias = "self-forming"
            keyPassword = selfFormingPassword
        }
    }
    buildTypes {
        debug {
            if (selfFormingKeystore != null) signingConfig = signingConfigs.getByName("selfForming")
        }
        release {
            // Published APKs: not debuggable (no run-as access to the app data). Same Self Forming key as debug builds,
            // so installed apps keep updating in place; without the env key build-apk.sh --release signs afterwards.
            isDebuggable = false
            isMinifyEnabled = false
            if (selfFormingKeystore != null) signingConfig = signingConfigs.getByName("selfForming")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    sourceSets.getByName("main").java.srcDirs(builtinDirs("src"))
    sourceSets.getByName("test").java.srcDirs(builtinDirs("test"))
    sourceSets.getByName("androidTest").java.srcDirs(builtinDirs("androidTest"))
    sourceSets.getByName("main").assets.srcDir(generatedAssets)
    // scripts/pack-source.sh: the repository itself, so the installed app can rebuild and update itself.
    sourceSets.getByName("main").assets.srcDir(layout.buildDirectory.dir("generated/selfSource"))
    sourceSets.getByName("main").assets.srcDir(rootProject.layout.projectDirectory.dir("../../dist/runtime/assets"))
    sourceSets.getByName("main").jniLibs.srcDir(rootProject.layout.projectDirectory.dir("../../dist/runtime/jniLibs"))
    packaging { jniLibs { useLegacyPackaging = true; keepDebugSymbols += setOf("**/*.so") } }
    testOptions { unitTests.isReturnDefaultValues = true }
}
androidComponents {
    onVariants { variant ->
        variant.sources.java?.addGeneratedSourceDirectory(generateBuiltinNatives, GenerateBuiltinNatives::output)
        builtinNative.map { it.resolve("manifest.xml") }.filter { it.isFile }
            .forEach { variant.sources.manifests.addStaticManifestFile(it.path) }
    }
}
kotlin { compilerOptions { jvmTarget = org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17 } }
tasks.named("preBuild").configure {
    dependsOn(syncBrowserAssets)
    doFirst {
        if (signingRequired) check(layout.buildDirectory.file("generated/selfSource/self-source/source.zip").get().asFile.isFile) {
            "Distributed APKs require their self-rebuild source. Run scripts/pack-source.sh before Gradle."
        }
        for (abi in listOf("arm64-v8a")) {
            val runtime = rootProject.file("../../dist/runtime")
            check(runtime.resolve("assets/runtime/ubuntu-$abi.zip").isFile &&
                runtime.resolve("assets/runtime/ubuntu-$abi.json").isFile &&
                runtime.resolve("jniLibs/$abi/libproot.so").isFile &&
                runtime.resolve("jniLibs/$abi/libproot-loader.so").isFile) {
                "Ubuntu/PRoot payload missing for $abi. Run scripts/fetch-runtime.sh first."
            }
        }
    }
}

