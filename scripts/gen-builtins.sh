#!/bin/bash
# Generates apps/common/builtin-plugins.js, the static registry of the built-in plugins
# (docs/plugins.md §3a): one `import * as` of each plugins/<id>/web/index.js plus that
# plugin's plugin.json as a literal, so start-up and the bundled fallback stay synchronous.
# Also generates apps/common/builtin-styles.css (T2): one @import of every stylesheet the manifests
# list under "styles" ({href, order}, relative to the plugin's web folder), sorted by order then id.
# index.html links it right after app.css, so the built-in plugins' CSS (and the look) is there
# on the first paint and when composition fails.
# Deterministic (sorted, no timestamps); the result is checked in. Usage:
#   scripts/gen-builtins.sh            write apps/common/builtin-plugins.js
#   scripts/gen-builtins.sh --check    fail if a checked-in file is stale
#   scripts/gen-builtins.sh --stdout   print the registry instead of writing
#   scripts/gen-builtins.sh --stdout-styles   print builtin-styles.css instead of writing
# Needs bash and jq only. Plugins matched by a `plugins/...` line of the private-only file
# of the editions directory (see its README) go into marker-delimited private blocks,
# so the public export carries exactly the registry this script makes without them.
# The marker words are assembled below: a literal marker line would be taken for a marker.
set -euo pipefail
cd "$(dirname "$0")/.."
out=apps/common/builtin-plugins.js
styles_out=apps/common/builtin-styles.css
mode=write
case "${1:-}" in --check) mode=check ;; --stdout) mode=stdout ;; --stdout-styles) mode=stdout-styles ;; "") ;; *) echo "usage: $0 [--check|--stdout]" >&2; exit 2 ;; esac
export LC_ALL=C
word=edition
start="$word:private:start"
end="$word:private:end"

patterns=()
list=$(printf '%ss/private-only.txt' "$word")
if [[ -f $list ]]; then
  while IFS= read -r line || [[ -n $line ]]; do
    line=${line%$'\r'}
    [[ $line == plugins/* ]] && patterns+=("$line")
  done < "$list"
fi
is_private() { # plugin id
  local pattern
  # shellcheck disable=SC2053 # glob match on purpose
  for pattern in "${patterns[@]}"; do [[ "plugins/$1/plugin.json" == $pattern ]] && return 0; done
  return 1
}

public=(); private=()
for manifest in plugins/*/plugin.json; do
  [[ -f $manifest ]] || continue
  id=$(basename "$(dirname "$manifest")")
  [[ $(jq -r .id "$manifest") == "$id" ]] || { echo "gen-builtins: $manifest: id does not match its folder" >&2; exit 1; }
  [[ $(jq -r '.web.entry // empty' "$manifest") == web/index.js && -f plugins/$id/web/index.js ]] || { echo "gen-builtins: plugins/$id: needs web/index.js as web.entry" >&2; exit 1; }
  [[ $(jq -r .builtin "$manifest") == true ]] || { echo "gen-builtins: $manifest: \"builtin\": true is missing" >&2; exit 1; }
  if is_private "$id"; then private+=("$id"); else public+=("$id"); fi
done
[[ ${#public[@]} -gt 0 ]] || { echo "gen-builtins: no plugins found" >&2; exit 1; }
mapfile -t public < <(printf '%s\n' "${public[@]}" | sort)
[[ ${#private[@]} -eq 0 ]] || mapfile -t private < <(printf '%s\n' "${private[@]}" | sort)
ident() { printf '%s' "${1//-/_}"; }

# T2/N1: the looks (plugins that provide look@1), lowest priority first; keep equal to STYLE_ONLY_PLUGINS in apps/common/plugin-builtins.js
# (a test checks it). The DEFAULT look is the last one present in the tree: only its stylesheet is imported by builtin-styles.css
# (first paint); any other look present is linked by plugin-styles.js while it is the selected provider.
looks=(look-public look-private)
default_look=
for id in "${looks[@]}"; do if [[ -f plugins/$id/plugin.json ]]; then default_look=$id; fi; done
# The public export carries no private plugin, so when the default look is private the public export's default look (the last
# PUBLIC look present) is imported inside a public-edition comment block (plain content in the export, a comment here).
public_look=
for id in "${looks[@]}"; do if [[ -f plugins/$id/plugin.json ]] && ! is_private "$id"; then public_look=$id; fi; done
is_other_look() { local id; for id in "${looks[@]}"; do [[ $1 == "$id" && $1 != "$default_look" ]] && return 0; done; return 1; }

emit() {
  cat <<'HEAD'
// GENERATED by scripts/gen-builtins.sh from plugins/*/plugin.json - do not edit; run the
// script after adding, removing or changing a built-in plugin (tests check it is current).
// The static registry of the built-in plugins (docs/plugins.md §3a): every plugin's web entry
// is imported statically, so start-up and the bundled fallback stay synchronous. Built-ins
// never go through plugins.install. The files are served next to the app files as
// builtin/<id>/web/** (the repository folder plugins/<id>/ without its manifest); the
// path /assets/web/plugins/<id>/<hash>/ stays reserved for installed plugins.
// Entries must not import a library module at evaluation (lazy import() in setup/load).
HEAD
  for id in "${public[@]}"; do printf 'import * as %s from "./builtin/%s/web/index.js";\n' "$(ident "$id")" "$id"; done
  if [[ ${#private[@]} -gt 0 ]]; then
    printf '// %s\n' "$start"
    for id in "${private[@]}"; do printf 'import * as %s from "./builtin/%s/web/index.js";\n' "$(ident "$id")" "$id"; done
    printf '// %s\n' "$end"
  fi
  printf '\n/** [{manifest: plugin.json, entry: the web entry module namespace}], sorted by id. */\n'
  printf 'export const BUILTIN_PLUGINS = Object.freeze([\n'
  for id in "${public[@]}"; do printf '  Object.freeze({ manifest: Object.freeze(%s), entry: %s }),\n' "$(jq -cS . "plugins/$id/plugin.json")" "$(ident "$id")"; done
  if [[ ${#private[@]} -gt 0 ]]; then
    printf '  // %s\n' "$start"
    for id in "${private[@]}"; do printf '  Object.freeze({ manifest: Object.freeze(%s), entry: %s }),\n' "$(jq -cS . "plugins/$id/plugin.json")" "$(ident "$id")"; done
    printf '  // %s\n' "$end"
  fi
  printf ']);\n'
  cat <<'TAIL'

/** The registry item of one built-in plugin id, or undefined. */
export const builtinPlugin = (id) => BUILTIN_PLUGINS.find((item) => item.manifest.id === id);
TAIL
}

emit_styles() {
  cat <<'HEAD'
/* GENERATED by scripts/gen-builtins.sh from the "styles" of every plugins/<id>/plugin.json - do not edit; run the
   script after adding, removing or changing a built-in plugin's styles (tests check it is current).
   The bundled stylesheet of the built-in plugins (T2): index.html links it right after app.css, so every
   built-in's CSS (and the DEFAULT look only: look-private where present, else look-public; other looks are linked by plugin-styles.js when selected) is applied on the first paint
   and when plugin composition fails. Sorted by order, then plugin id; the plugins' own "styles"
   contributions are the same files (plugin-styles.js does not link them a second time). */
HEAD
  local lines=() id href order state=public tab=$'\t'
  for id in "${public[@]}" "${private[@]}"; do
    if is_other_look "$id" && ! { [[ $id == "$public_look" ]] && is_private "$default_look"; }; then continue; fi
    while IFS=$'\t' read -r order href; do
      [[ -n $href ]] || continue
      [[ -f plugins/$id/web/$href ]] || { echo "gen-builtins: plugins/$id: styles file web/$href is missing" >&2; exit 1; }
      lines+=("$order$tab$id$tab$href$tab$(if is_other_look "$id"; then echo 2; elif is_private "$id"; then echo 1; else echo 0; fi)")
    done < <(jq -r '(.styles // [])[] | [(.order // 0), .href] | @tsv' "plugins/$id/plugin.json")
  done
  [[ ${#lines[@]} -gt 0 ]] || return 0
  local order2 id2 href2 priv
  while IFS=$'\t' read -r order2 id2 href2 priv; do
    if [[ $priv == 2 ]]; then
      if [[ $state == private ]]; then printf '/* %s */\n' "$end"; state=public; fi
      printf '/* %s:public:start\n@import url("./builtin/%s/web/%s");\n%s:public:end */\n' "$word" "$id2" "$href2" "$word"
      continue
    fi
    if [[ $priv == 1 && $state == public ]]; then printf '/* %s */\n' "$start"; state=private; fi
    if [[ $priv == 0 && $state == private ]]; then printf '/* %s */\n' "$end"; state=public; fi
    printf '@import url("./builtin/%s/web/%s");\n' "$id2" "$href2"
  done < <(printf '%s\n' "${lines[@]}" | sort -t"$tab" -k1,1n -k2,2 -k3,3)
  if [[ $state == private ]]; then printf '/* %s */\n' "$end"; fi
}

# The plugins skill: single source plugins/core-plugin-management/web/skills/plugins/SKILL.md. Generated from it:
# skills/plugins/SKILL.md (source-tree readers, the Android path) and web/plugins-skill-text.js (seeded into the
# browser workspace by index.js, where nothing unpacks the source tree).
skill_src=plugins/core-plugin-management/web/skills/plugins/SKILL.md
skill_copy=skills/plugins/SKILL.md
skill_js=plugins/core-plugin-management/web/plugins-skill-text.js
emit_skill_js() {
  printf '// GENERATED by scripts/gen-builtins.sh from web/skills/plugins/SKILL.md - do not edit.\nexport default %s;\n' "$(jq -Rs . "$skill_src")"
}

case $mode in
  stdout) emit ;;
  stdout-styles) emit_styles ;;
  write) emit > "$out.tmp"; cp "$skill_src" "$skill_copy"; emit_skill_js > "$skill_js"; mv "$out.tmp" "$out"; emit_styles > "$styles_out.tmp"; mv "$styles_out.tmp" "$styles_out"; echo "gen-builtins: wrote $out (${#public[@]} public, ${#private[@]} private-only plugins) and $styles_out" ;;
  check) emit | cmp -s - "$out" || { echo "gen-builtins: $out is stale; run scripts/gen-builtins.sh" >&2; exit 1; }
    emit_styles | cmp -s - "$styles_out" || { echo "gen-builtins: $styles_out is stale; run scripts/gen-builtins.sh" >&2; exit 1; }
    cmp -s "$skill_src" "$skill_copy" && emit_skill_js | cmp -s - "$skill_js" || { echo "gen-builtins: $skill_copy or $skill_js is stale; run scripts/gen-builtins.sh" >&2; exit 1; } ;;
esac
